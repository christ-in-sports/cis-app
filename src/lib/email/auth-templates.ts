/**
 * The Supabase Auth email templates, built from the shared `emailLayout` so they
 * match the Resend emails and the app's palette.
 *
 * Supabase reads them as files (`supabase/config.toml` points at
 * `supabase/templates/*.html`), so they are generated, not hand-edited:
 *
 *   npm run emails:build
 *
 * writes the files, and `auth-templates.test.ts` fails if a committed file no
 * longer matches what is built here. The `{{ .Token }}` style placeholders are
 * Supabase's Go template variables, filled in when Auth sends the email.
 *
 * Local Supabase picks the files up from `config.toml`. The hosted project does
 * not: paste each file into Authentication → Email Templates after a change.
 */

import { button, codeBox, emailLayout, heading, heavyRule, note, paragraph } from './layout';

const LOGO = '{{ .SiteURL }}/assets/fish-mark.png';

/** The one-time code emails. The code is the whole message: no link, because on
 * a phone a link opens in the mail app's own browser and the sign-in lands in
 * the wrong place (ENG-28). */
function codeEmail(comment: string): string {
  return `<!-- ${comment}
     Generated by \`npm run emails:build\` from src/lib/email/auth-templates.ts; edit that, not this file. -->
${emailLayout({
  title: 'Your Christ in Sports code',
  preheader: 'Your sign-in code is inside. It expires in an hour.',
  logoUrl: LOGO,
  body: [
    heading('Your sign-in code'),
    heavyRule(),
    paragraph('Type this code into the app to sign in:', { first: true }),
    codeBox('{{ .Token }}'),
    note('It works once and expires in an hour. If you did not ask for it, you can ignore this email.'),
  ],
})}`;
}

export interface AuthTemplate {
  /** File name in `supabase/templates/`. */
  file: string;
  /** The subject set beside it in `config.toml` (and the hosted dashboard). */
  subject: string;
  html: string;
}

